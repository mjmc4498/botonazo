const TAG = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/>/g;
const ATTR = /([a-zA-Z-]+)="([^"]*)"/g;

// Convierte un ícono en [[etiqueta, {atributo: valor}], …] para enviarlo al celular.
export function iconShapes(name) {
  const src = ICONS[name];
  if (!src) return null;
  const shapes = [];
  for (const [, tag, attrs] of src.matchAll(TAG)) {
    const a = {};
    for (const [, k, v] of attrs.matchAll(ATTR)) a[k] = v;
    shapes.push([tag, a]);
  }
  return shapes;
}

export function iconSvg(name, cls = '') {
  const src = ICONS[name] || ICONS.zap;
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true">${src}</svg>`;
}
